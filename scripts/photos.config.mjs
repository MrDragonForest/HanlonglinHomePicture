/**
 * 照片处理配置。
 *
 * sources  —— 原始照片所在目录（相对项目根目录）。这些目录已在 .gitignore 中排除，
 *             仓库里只保留压缩后的 public/photos/ 衍生图。
 *             后续想从别的文件夹导入，把路径加进这个数组即可。
 */
export const config = {
  // 一个批次对应一个「相册分组」，会写进清单里
  batches: [
    {
      album: '我们的 2026',
      sources: ['韩龙林 于长春'],
    },
  ],

  // 输出目录（相对项目根目录）
  outDir: 'public/photos',
  manifestFile: 'src/data/photos.json',

  /**
   * 每一档都是「图片宽度」，不是长边。
   *
   * 为什么要多档：手机上 1 个 CSS 像素可能对应 3 个物理像素，
   * 只生成一档固定尺寸的话，Retina 屏拿到的是被拉伸的糊图。
   * 生成一条阶梯 + 前端写 srcset/sizes，浏览器会自己挑一档，
   * 保证「显示的像素数 ≥ 需要的物理像素数」，也就是永远不放大。
   *
   * 档位按 1.5 倍递增：相邻两档最多过采样 1.5 倍，
   * 档位太密文件数会翻倍，太疏就会挑到明显偏大的一档。
   */
  ladder: [420, 640, 960, 1440],

  /**
   * 横图多一档。
   *
   * 竖图进全屏查看器时是「高度撑满、宽度窄」，所以 1440 就够；
   * 横图是「高度撑满、宽度撑开」（1.5:1 的图在 1440 宽的窗口里能到 900+ CSS 宽），
   * Retina 屏需要 1800 设备像素，只有 1440 会被放大 1.26 倍，所以补一档。
   */
  wideLadder: [420, 640, 960, 1440, 1920],

  /**
   * 全景图在排版里是整行铺满（见 useLayout 的 panorama 分支），
   * 宽度远超普通格子，所以要多一档更宽的。
   */
  panoramaLadder: [420, 960, 1440, 2880],

  // 所有档位共用一个画质。1440 宽这一档也兼任原来的「全屏查看」图。
  quality: 76,

  // LQIP：极小尺寸的模糊占位图，内联成 base64 直接写进清单，实现「先模糊后清晰」
  lqip: {
    edge: 24,
    quality: 32,
  },

  // 只处理这些扩展名。HEIC/HEIF 不在列表里：sharp 的预编译包不含 HEIC 解码器（授权原因）。
  extensions: ['.jpg', '.jpeg', '.png', '.webp', '.tif', '.tiff'],

  // 并发处理的图片数量
  concurrency: 4,
}
